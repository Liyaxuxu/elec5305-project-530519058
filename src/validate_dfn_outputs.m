function available = validate_dfn_outputs(cases, folder)
%VALIDATE_DFN_OUTPUTS Check all reference WAVs before starting the experiment.
% No matching files means the optional reference is skipped. A partial or
% invalid set stops the run so it cannot produce an incomplete comparison.
% These checks validate the audio files, not which model or input made them.
paths = arrayfun(@(c) fullfile(folder, 'enhanced', c.id + ".wav"), ...
    cases, 'UniformOutput', false);
present = cellfun(@isfile, paths);
available = any(present);
if ~available, return; end
assert(all(present), 'validate_dfn_outputs:Incomplete', ...
    'DeepFilterNet outputs are incomplete (%d/%d). Rerun the Python step for %s.', ...
    sum(present), numel(cases), folder);
for k = 1:numel(cases)
    [audio, rate] = audioread(paths{k});
    assert(rate == cases(k).fs && size(audio, 2) == 1 && ...
        size(audio, 1) == numel(cases(k).noisy) && all(isfinite(audio), 'all'), ...
        'validate_dfn_outputs:InvalidAudio', ...
        'Invalid DeepFilterNet output: %s. Expected finite mono audio at %d Hz with %d samples.', ...
        paths{k}, cases(k).fs, numel(cases(k).noisy));
end
end
